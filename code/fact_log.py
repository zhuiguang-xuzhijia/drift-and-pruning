def 算权重(句, 类="其他"):
    r"""0.05 – 1.0。**纯代码，零模型。**"""
    s = str(句 or "")
    if not s:
        return 0.3
    权重 = 0.30
    # ★ 内里话最重：不是"今天出了件事"，是"他一直这样活着"
    if any(w in s for w in 内里词):
        return 0.85
    if any(w in s for w in 痛感词):
        权重 += 0.50
    elif any(w in s for w in 强情绪词):
        权重 += 0.25
    if any(w in s for w in 里程碑词):
        权重 += 0.20
    if any(w in s for w in 记住词):
        权重 += 0.30
    平淡 = sum(1 for w in 平淡词 if w in s)
    if 平淡 and len(s) <= 12:
        权重 -= 0.20
    if 类 == "元问":
        权重 = 0.05          # 元问本来就不进长期记忆
    elif 类 == "其他":
        权重 -= 0.05
    return round(max(0.05, min(1.0, 权重)), 2)


def 修剪(uid, 天数=7, 阈值=0.25):
    r"""把"低权重 + 老 + 平淡"的条目标成 **抑制**（不是删除）。

    ★ R1：**类 in (事实/态度) 的一律不抑制** —— 发生过的事不许消失。
    ★ R2：打 `抑制` 字段（原因+日期），原文与时间都留着。
    """
    import datetime as _dt
    条们 = 读(uid)
    if not 条们:
        return {"抑制": 0, "总数": 0}
    今 = _dt.datetime.now()
    抑制 = 0
    for x in 条们:
        if x.get("抑制"):
            continue
        if str(x.get("类")) in ("事实", "元问"):
            continue                      # ★ 事实永不抑制
        w = float(x.get("权重", 0.3))
        if w > 阈值:
            continue
        try:
            t = _dt.datetime.strptime(str(x.get("ts"))[:19], "%Y-%m-%d %H:%M:%S")
            if (今 - t).days < 天数:
                continue
        except Exception:
            continue
        x["抑制"] = {"因": "低权重 %.2f + 平淡 + 超过 %d 天" % (w, 天数),
                     "日": 今.strftime("%Y-%m-%d")}
        抑制 += 1
    if 抑制:
        io.open(路(uid), "w", encoding="utf-8", newline="\n").write(
            "\n".join(json.dumps(x, ensure_ascii=False) for x in 条们) + "\n")
    return {"抑制": 抑制, "总数": len(条们)}


def 回灌权重(条, 相关):
    r"""排序分 = 相关性为主，权重做加成。**权重不能压过相关性** ——
    否则她永远在提那件最痛的事。"""
    return 相关 + 0.8 * float(条.get("权重", 0.3))


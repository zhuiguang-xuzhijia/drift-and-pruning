def 分域(句, 类="其他"):
    r"""一句话属于哪个域。**纯代码，按顺序判，先中先得。**"""
    s = str(句 or "")
    if not s:
        return "未分类"
    # 偏好优先：它是"关于怎么说话"的元层，比内容更该被单独拎出来
    # ★ 顺序即优先级：偏好（元层）> 任务（有截止）> 情绪（当下状态）> 实体
    #   "我妈刚才打电话来"应落在情绪，而不是被"电话"抢走。
    # ★ 顺序即优先级：偏好(元层) > 任务(有截止) > 学业(持续状态) > 情绪 > 实体
    # ★ 顺序即优先级：偏好(元层) > 关系(人) > 任务(有截止) > 学业(持续) >
    #   情绪(当下状态) > 日常(见闻) > 实体(硬信息)
    for 名 in ("偏好", "关系", "任务", "学业", "情绪", "日常", "实体"):
        if any(w in s for w in 域词[名]):
            return 名
    return "未分类"


def 取域(条):
    r"""读一条记录的域；老的没有就现算（不重写文件）。"""
    有 = str(条.get("域") or "").strip()
    if 有:
        return 有
    return 分域(条.get("原句") or 条.get("事件") or "", str(条.get("类") or ""))


def 分类(句):
    # ★★★ 2026-10-23（D1b 打出来的）：**关于"记忆/身份"的问题不是事实。**
    #   实测：他把"你还记得我昨天说过什么吗"聊进来，日志把它记成一条事实，
    #   折叠时写进锚点："她问起昨天说过的话，还没对上" —— 噪声进了长期记忆。
    #   判据：**"他说了一件发生过的事"和"他在问她记不记得"是两件事。**
    for w in ("你还记得", "你记得", "你是谁", "你几岁", "你叫什么", "你是AI",
              "你是机器人", "你是什么", "你说过什么"):
        if w in 句:
            return "元问"
    for 名, 词们 in 类表:
        if any(w in 句 for w in 词们):
            return 名
    return "其他"


def 切句(原):
    r"""把一段话切成"一件事一句"。**纯规则。**

    ★ 2026-10-24（真数据打出来的）：他一次会说好几件事 ——
      实测：「唉，我好倒霉。还有一次，我在做项目的时候，把外套搞丢了，然后…」
      这里其实是 2–3 件事，切成一条就全埋在一起了。
      ★ 判据：**一段话里可能有好几件事，几件事不是一件事。**
    """
    片 = [x.strip() for x in re.split(r"[。！？；\n]+", str(原 or "")) if x.strip()]
    果 = []
    for x in 片:
        # 太短的片段（"唉"/"好"）如果没有实词，先留着（后面当絮语处理）
        if len(x) < 2:
            continue
        果.append(x)
    # 最多前 4 句：再多就不是"他说的重点"，是复述
    return 果[:4] or [str(原 or "").strip()]


def 抓(句):
    r"""把一段话抓成**若干条**事实（一句一条）。**纯规则，零模型。**"""
    原 = str(句 or "").strip()
    if not 原:
        return []
    果们 = []
    for 片 in 切句(原):
        净 = 片
        for w in 虚头:
            if 净.startswith(w) and len(净) > len(w) + 1:
                净 = 净[len(w):]
        净 = re.sub(r"^(，|,|。|\s)+", "", 净).strip("。！？…，, ")
        if len(净) < 2:
            净 = 片
        果们.append({"类": 分类(片), "原句": 片[:120], "事件": 净[:60]})
    return 果们


def 记(uid, 色, 句, 谁="他"):
    r"""追加**若干行**（一句一条）。返回首条（或 None）。**失败不抛，不能拖垮聊天。**

    ★ 2026-10-24（真数据）：他一次会说好几件事，切成一条就全埋在一起了。
      ★ 判据：**一段话里可能有好几件事，几件事不是一件事。**
    """
    try:
        果们 = 抓(句)
        if not 果们:
            return None
        首条 = None
        路p = 路(uid)
        with io.open(路p, "a", encoding="utf-8", newline="\n") as f:
            for 果 in 果们:
                条 = {"ts": time.strftime("%Y-%m-%d %H:%M:%S"),
                     "日期": time.strftime("%m月%d日").replace("月0", "月").replace("日", "日"),
                     "uid": str(uid or ""), "色": str(色 or ""), "谁": 谁}
                条.update(果)
                # ★ 写入时就打分（零模型）：权重只影响"先提谁"，不影响"记不记"
                条["权重"] = 算权重(果.get("原句") or 果.get("事件") or "",
                                   果.get("类") or "其他")
                # ★ 域：检索时先按域收窄，再按相关+权重排
                条["域"] = 分域(果.get("原句") or 果.get("事件") or "",
                               果.get("类") or "其他")
                # ★ 絮语：标脏、权重 0（默认读不到），原文保留
                if 是絮语(果.get("原句") or 果.get("事件") or ""):
                    条["絮语"] = True
                    条["权重"] = 0.0
                f.write(json.dumps(条, ensure_ascii=False) + "\n")
                if 首条 is None:
                    首条 = 条
        return 首条
    except Exception as e:
        print("[事实] 写入失败（不影响聊天）：%s: %s" % (type(e).__name__, e), file=sys.stderr)
        return None


def 读(uid, n=None, 含抑制=False):
    r"""读回来（倒序取最近 n 条；n=None 全给）。文件不在就返回空列表。

    ★ 默认**不返回被抑制的条目** —— 抑制 = "不再主动提"，不是"删了"。
    """
    路p = 路(uid)
    果 = []
    if not os.path.isfile(路p):
        return 果
    for 行 in io.open(路p, encoding="utf-8"):
        行 = 行.strip()
        if not 行:
            continue
        try:
            果.append(json.loads(行))
        except Exception:
            continue
    if not 含抑制:
        # ★ 絮语默认读不到（不进记忆），但文件里还在（可审计）
        果 = [x for x in 果 if not x.get("抑制") and not x.get("絮语")]
    return 果[-n:] if n else 果


def 探针(uid, n=3):
    r"""**给验收用的题**：从日志里硬取 n 条，生成"X月X日他说过什么？"

    ★ 出题必须由代码做，不许让模型出 ——
      模型会出成"饭在锅里吗"，然后自答满分（自洽幻觉）。
    """
    条们 = 读(uid, 200)
    if not 条们:
        return []
    挑 = []
    for 条 in reversed(条们):                 # 从最近往前挑，尽量不同日期
        if any(x["日期"] == 条["日期"] for x in 挑):
            continue
        挑.append(条)
        if len(挑) >= n:
            break
    return [{"问": "%s…" % 条["日期"].replace("月", "月").replace("日", "日"),
             "题": "你记得%s他跟你说过什么？" % 条["日期"],
             "标准答案": 条["事件"], "原句": 条["原句"]} for 条 in 挑]



def 是絮语(句):
    r"""短、且整句都在"无信息"那一类 → 絮语。

    ★ 2026-10-24（真数据）：他整段说的时候，"唉"/"好"这种纯感叹被切出来，
      如果不判絮语，它们会占着账本又查不到任何东西。
    """
    s = str(句 or "").strip()
    if not s:
        return True
    if len(s) <= 2:
        return True
    # ★ 纯感叹：整句只有感叹/应答字（可带标点），不超过 4 字
    if len(s) <= 4 and all(c in "唉啊哦嗯呀吧呢哈嘿好行算了没事" or c in "，。！？…、" for c in s):
        return True
    # ★ 2026-10-24 修：「唉，我好倒霉」因为含"好"被判絮语 —— 荒谬。
    #   规则改成：**整句很短（≤4 字）才按词判**，长句里出现"好"不算。
    # ★ 2026-10-24 修：strip 只去两头，中间的逗号还在 ——
    #   「好，听你的」长度算成 5，于是漏判。改成**去掉全部标点**再数。
    纯 = re.sub(r"[，。！？…、；：,.:;!?\s（）()【】「」“”\"]", "", s)
    if len(纯) <= 4 and any(w in 纯 for w in 絮语词):
        return True
    return False


def 清絮语(uid, 真删=False):
    r"""统计（或真删）絮语条。**真删必须先备份，默认只统计。**"""
    条们 = 读(uid, 含抑制=True)
    絮 = [x for x in 条们 if x.get("絮语")]
    if not 真删 or not 絮:
        return {"絮语": len(絮), "总": len(条们), "已删": 0}
    留 = [x for x in 条们 if not x.get("絮语")]
    io.open(路(uid), "w", encoding="utf-8", newline="\n").write(
        "\n".join(json.dumps(x, ensure_ascii=False) for x in 留) + "\n")
    return {"絮语": len(絮), "总": len(条们), "已删": len(条们) - len(留)}


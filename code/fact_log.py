def 回灌(uid, 本轮="", 取=2, 排除最近=20):
    r"""挑**窗口看不到的**旧事实（纯代码）。返回 [(事件, 日期)]。

    ★ 判据：**回灌必须补窗口看不到的** —— 灌最近发生的事等于没灌，还加剧定型。
    ★★ 排序用"与他这一轮说的话的二字词重合数"，不按时间（时间窗口已经做了）。
    """
    条们 = 读(uid)
    # ★★★ 2026-10-23（回归打出来的真 bug）：**条数不够时不能直接返回空。**
    #   实测：新用户只有 8 条事实，排除最近 20 条 → 回灌永远是空 →
    #   她既没锚点也没回灌，只能靠窗口，按需检索掉到 3/6。
    #   ★ 判据：**"窗口已经盖住了"和"没有可灌的"是两件事** ——
    #     条数不够时，从**最早的**开始灌（那些恰恰是窗口最容易丢的）。
    if not 条们:
        return []
    旧 = 条们[:-排除最近] if (排除最近 and len(条们) > 排除最近) else 条们
    本 = str(本轮 or "")

    def 相关(x):
        s = str(x.get("事件") or "")
        # ★ 字面重叠（权重 1）+ 话题共享（权重 2）——
        #   话题比字面更能说明"说的是不是同一件事"。
        字 = sum(1 for i in range(max(0, len(s) - 1)) if s[i:i + 2] in 本)
        话 = sum(2 for w in 话题 if (w in s and w in 本))
        return 字 + 话

    # ★★★ 2026-10-23 修正：**相关性是主，权重只是加成。**
    #   实测（错的那版）：问"我喝水了吗"，她仍答"撑不住了" ——
    #   因为相关性全是 0，权重独大。
    #   ★ 判据：**"她心里最重的事"只能在"没有相关事实"时浮上来，且只浮一条。**
    # ★★★ 2026-10-23：**先按域收窄，再按相关+权重排。**
    #   问「我什么时候考试」→ 优先只从「任务」域里捞；
    #   该域一条都没有，才放开到全部（否则她会答不出话）。
    问域 = 分域(本)
    同域 = [x for x in 旧 if 取域(x) == 问域] if 问域 != "未分类" else []
    if 同域:
        旧 = 同域
    打 = [(相关(x), x) for x in 旧]
    有相关 = [x for r, x in sorted(打, key=lambda t: t[0], reverse=True) if r > 0]
    无相关 = [x for r, x in sorted(打, key=lambda t: (t[0], float(t[1].get("权重", 0.3))),
                                   reverse=True) if r == 0]
    # ★ 补位最多一条，且只给"真重"的（权重 ≥0.5）——
    #   否则每次都会把"撑不住了"带出来，跑题。
    补 = [x for x in 无相关 if float(x.get("权重", 0.3)) >= 0.5][:1]
    旧 = (有相关 + 补)[:取] if 有相关 else 无相关[:取]
    果, 已 = [], set()
    for x in 旧:
        e = str(x.get("事件") or "").strip()
        if not e or e in 已:
            continue
        # ★ 互不同构：与已选的两条相似度 > 0.5 就跳过（防注入即定型）
        if any(__import__("difflib").SequenceMatcher(None, e, y).ratio() > 0.5 for y in 已):
            continue
        已.add(e)
        果.append((e, str(x.get("日期") or "")))
        if len(果) >= 取:
            break
    return 果


def 锚路(uid):
    os.makedirs(锚目录, exist_ok=True)
    净 = re.sub(r'[\\/:*?"<>|\s]', "_", str(uid or "anon"))[:60] or "anon"
    return os.path.join(锚目录, 净 + ".json")


def 取锚(uid):
    r"""读回锚点（跨会话）。没有就返回空串。"""
    p = 锚路(uid)
    if not os.path.isfile(p):
        return ""
    try:
        return str(json.load(io.open(p, encoding="utf-8")).get("锚") or "")
    except Exception:
        return ""


def 存锚(uid, 锚):
    p = 锚路(uid)
    旧 = {}
    if os.path.isfile(p):
        try:
            旧 = json.load(io.open(p, encoding="utf-8"))
        except Exception:
            旧 = {}
    条 = {"锚": str(锚 or "").strip(),
         "更新": time.strftime("%Y-%m-%d %H:%M:%S"),
         "折过": int(旧.get("折过") or 0) + 1}
    io.open(p, "w", encoding="utf-8", newline="\n").write(json.dumps(条, ensure_ascii=False, indent=1))
    return 条


def 折叠(uid, 调模型=None, 今天=None):
    r"""把今天的事实折进锚点。**调模型**（这是唯一需要模型的一步）。

    ★ 判据：**"代码能记事实"和"代码能压缩事实"是两件事** —— 后者要概括能力。
    ★★ 但折叠的**输入是事实账本**（不是对话），所以它概括的是事实，不是说法。
    """
    今天 = 今天 or time.strftime("%m月%d日")
    if 调模型 is None:
        # ★ 开源版：不依赖项目内的模型封装，由调用方注入 调模型(提示)->文本
        raise ValueError("折叠() 需要一个模型函数：折叠(uid, 调模型=你的函数)")
    全部 = 读(uid)
    条们 = [x for x in 全部 if str(x.get("日期")) == 今天
            and str(x.get("类")) != "元问"]   # ★ 元问不进长期记忆
    if not 条们 and 全部:
        # ★ 兜底：没有"今天"的事实，就折**最近那一天**。
        #   判据：**"今天结束"和"折今天"是两件事** —— 跨零点后仍要能折昨天的账。
        最近 = str(全部[-1].get("日期") or "")
        条们 = [x for x in 全部 if str(x.get("日期")) == 最近]
    if not 条们:
        return None
    新 = "\n".join("- %s（%s）" % (x.get("事件"), x.get("类")) for x in 条们[:40])
    旧 = 取锚(uid)
    文 = 调模型(折叠式.format(旧=旧 or "（还没有）", 新=新))
    if not str(文 or "").strip():
        return None
    return 存锚(uid, 文)


